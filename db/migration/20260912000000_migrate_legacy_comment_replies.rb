  def validate_reply!(reply, parent, parent_id)
    raise "Comment #{reply.id} already has parent #{reply.parent_id}" if reply.parent_id.present?
    raise "Comment #{reply.id} has an unexpected author" unless AUTHOR_NAMES.include?(reply.name.to_s.strip)
    raise "Comment #{reply.id} and parent #{parent_id} belong to different entries" unless reply.entry_id == parent.entry_id
    raise "Comment #{reply.id} and parent #{parent_id} have different visibility" unless reply.private? == parent.private?
    comparison = [parent.created_at, parent.id] <=> [reply.created_at, reply.id]
    raise "Comment #{parent_id} is not older than reply #{reply.id}" unless comparison == -1
  end
